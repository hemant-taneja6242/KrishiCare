"""
seed_demo.py — Populate KrishiCare DB with rich prototype demo data.

Run with:
    .\\venv\\Scripts\\activate
    python seed_demo.py

Clears all existing data and re-seeds:
  - 1 farmer farm (Hemant's farm in Ozar, Nashik — Tomato crop)
  - 12 diagnoses: 3 from the farmer's own farm + 9 for the expert queue
  - 3 alerts: auto-generated by create_alerts_for_diagnosis against the 1 farm
"""
import os, sys
sys.path.insert(0, os.path.dirname(__file__))

from datetime import datetime, timedelta
from models import init_db, SessionLocal, Farm, Diagnosis, Alert

def ago(days=0, hours=0, minutes=0):
    return datetime.utcnow() - timedelta(days=days, hours=hours, minutes=minutes)

def main():
    init_db()
    db = SessionLocal()

    try:
        # Wipe existing demo data
        db.query(Alert).delete()
        db.query(Diagnosis).delete()
        db.query(Farm).delete()
        db.commit()
        print("Cleared existing data.")

        # ── 1. FARMER — single demo farm ─────────────────────────────
        farm = Farm(
            farmer_name="Hemant Taneja",
            latitude=19.9975,
            longitude=73.7898,
            primary_crop="Tomato",
            village="Ozar",
            district="Nashik",
            state="Maharashtra",
        )
        db.add(farm)
        db.commit()
        db.refresh(farm)
        print(f"Created farm id={farm.id}: {farm.farmer_name}, {farm.village}, {farm.district}")

        # ── 2. DIAGNOSES ──────────────────────────────────────────────
        diagnosis_data = [
            # --- Farmer's own scans (linked to farm) ---
            dict(farm_id=farm.id, crop="Tomato", disease_label="Early Blight",       diagnosis_type="disease", confidence=0.8274, severity="High",     expert_status="auto_confirmed", latitude=19.9975, longitude=73.7898, created_at=ago(hours=2)),
            dict(farm_id=farm.id, crop="Tomato", disease_label="Bacterial Spot",      diagnosis_type="disease", confidence=0.4218, severity="Low",      expert_status="pending",        latitude=19.9975, longitude=73.7898, created_at=ago(hours=14)),
            dict(farm_id=farm.id, crop="Tomato", disease_label="Healthy",             diagnosis_type="disease", confidence=0.9120, severity="None",     expert_status="auto_confirmed", latitude=19.9975, longitude=73.7898, created_at=ago(days=2)),

            # --- Expert queue — nearby farms (no farm_id) ---
            dict(farm_id=None, crop="Tomato",    disease_label="Late Blight",                  diagnosis_type="disease", confidence=0.5100, severity="High",     expert_status="pending",        latitude=19.9842, longitude=73.7612, created_at=ago(hours=1)),
            dict(farm_id=None, crop="Rice",      disease_label="Rice Blast",                   diagnosis_type="disease", confidence=0.3800, severity="Critical", expert_status="pending",        latitude=19.0760, longitude=74.7480, created_at=ago(hours=3)),
            dict(farm_id=None, crop="Wheat",     disease_label="Powdery Mildew",               diagnosis_type="disease", confidence=0.4500, severity="Medium",   expert_status="pending",        latitude=20.0112, longitude=73.9450, created_at=ago(hours=5)),
            dict(farm_id=None, crop="Potato",    disease_label="Early Blight",                 diagnosis_type="disease", confidence=0.6200, severity="High",     expert_status="approved",       latitude=19.5680, longitude=74.0012, created_at=ago(hours=8)),
            dict(farm_id=None, crop="Sugarcane", disease_label="Red Rot",                      diagnosis_type="disease", confidence=0.7800, severity="Critical", expert_status="approved",       latitude=17.6880, longitude=74.0123, created_at=ago(days=1)),
            dict(farm_id=None, crop="Cotton",    disease_label="Bacterial Blight",             diagnosis_type="disease", confidence=0.8900, severity="High",     expert_status="auto_confirmed", latitude=20.5510, longitude=75.0120, created_at=ago(days=1, hours=3)),
            dict(farm_id=None, crop="Tomato",    disease_label="Septoria Leaf Spot",           diagnosis_type="disease", confidence=0.2339, severity="Low",      expert_status="rejected",       latitude=19.9500, longitude=73.8200, created_at=ago(days=2)),
            dict(farm_id=None, crop="Grape",     disease_label="Powdery Mildew",               diagnosis_type="disease", confidence=0.5600, severity="Medium",   expert_status="pending",        latitude=20.1150, longitude=74.7320, created_at=ago(days=2, hours=6)),
            dict(farm_id=None, crop="Onion",     disease_label="Purple Blotch",                diagnosis_type="disease", confidence=0.6900, severity="High",     expert_status="pending",        latitude=18.3450, longitude=74.6780, created_at=ago(days=3)),
            dict(farm_id=None, crop="Rice",      disease_label="Sheath Blight",                diagnosis_type="disease", confidence=0.7200, severity="High",     expert_status="approved",       latitude=16.8900, longitude=74.4560, created_at=ago(days=3, hours=4)),
            dict(farm_id=None, crop="Corn",      disease_label="Northern Corn Leaf Blight",    diagnosis_type="disease", confidence=0.8100, severity="Critical", expert_status="auto_confirmed", latitude=18.5204, longitude=73.8567, created_at=ago(days=4)),
            dict(farm_id=None, crop="Wheat",     disease_label="Rust",                         diagnosis_type="disease", confidence=0.9100, severity="Critical", expert_status="auto_confirmed", latitude=21.1458, longitude=79.0882, created_at=ago(days=4, hours=2)),
        ]

        diags = []
        for d in diagnosis_data:
            obj = Diagnosis(**d)
            db.add(obj)
            diags.append(obj)
        db.commit()
        print(f"Created {len(diags)} diagnoses.")

        # ── 3. ALERTS — peer alerts pointing at the single farm ───────
        # Simulate auto-generated alerts from confirmed nearby diagnoses
        alert_data = [
            dict(
                diagnosis_id=diags[3].id,   # Late Blight near Ozar
                source_farm_id=None,
                target_farm_id=farm.id,
                message="Early Blight detected 0.3 km from your farm in Ozar. Inspect your Tomato leaves immediately.",
                radius_km=5.0,
                created_at=ago(hours=2),
            ),
            dict(
                diagnosis_id=diags[3].id,   # Late Blight — 2.8 km
                source_farm_id=None,
                target_farm_id=farm.id,
                message="Tomato Late Blight detected 2.8 km away in Niphad. Cool humid conditions — monitor for water-soaked spots.",
                radius_km=5.0,
                created_at=ago(hours=8),
            ),
            dict(
                diagnosis_id=diags[5].id,   # Powdery Mildew — 3.5 km
                source_farm_id=None,
                target_farm_id=farm.id,
                message="Powdery Mildew detected 3.5 km from your farm. Spray neem oil as a preventive measure.",
                radius_km=5.0,
                created_at=ago(days=1),
            ),
        ]
        for a in alert_data:
            db.add(Alert(**a))
        db.commit()
        print(f"Created {len(alert_data)} alerts.")

        print("\n✅ Demo seed complete!")
        print(f"   Farm: #{farm.id} Hemant Taneja — Tomato, Ozar-Nashik (lat={farm.latitude}, lon={farm.longitude})")
        print(f"   Diagnoses: {len(diags)} (3 farmer scans + 12 expert queue)")
        print(f"   Alerts: {len(alert_data)} peer alerts targeting farm #{farm.id}")
        print(f"\n   ℹ️  Map hotspots come from weather.py _mock_hotspots() (22 points, no DB needed)")

    finally:
        db.close()

if __name__ == "__main__":
    main()
